export interface NoticiaDelCalendario {
  tipo: TipoNoticia
  t: number // ms UTC de la publicación
  h: number // hora de Nueva York
  m: number
}

let porDia: Map<number, NoticiaDelCalendario[]> | null = null

/**
 * Las noticias de una sesión. Lo que sale de las 17:00 en adelante cae en la sesión siguiente, que abre a las 18:00:
 * si sale con el mercado cerrado (como el recorte del domingo 15 de marzo de 2020), la sesión abre con hueco.
 */
export function noticiasDelDia(dia: number): NoticiaDelCalendario[] {
  if (!porDia) {
    porDia = new Map()
    for (const tipo of TIPOS_NOTICIA)
      for (const x of FECHAS[tipo]) {
        const fecha = Math.floor(x / 10000)
        const h = Math.floor(x / 100) % 100
        const m = x % 100
        const sesion = h >= 17 ? sumarDias(fecha, 1) : fecha
        const lista = porDia.get(sesion) ?? []
        lista.push({ tipo, t: enNY(fecha, h, m), h, m })
        porDia.set(sesion, lista)
      }
    for (const lista of porDia.values())
      lista.sort((a, b) => a.t - b.t || TIPOS_NOTICIA.indexOf(a.tipo) - TIPOS_NOTICIA.indexOf(b.tipo))
  }
  return porDia.get(dia) ?? []
}

/** Si el tipo sale en el calendario de ese mercado. */
export const afecta = (tipo: TipoNoticia, clave: Clave) => {
  const m = DATOS[tipo].mercados
  return m === 'todos' || m.includes(clave)
}
